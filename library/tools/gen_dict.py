'''
Builds the T9 word list, library/arduino/src/t9kb_dict.c, from two sources:

  Ranking: top_english_words_lower_50000.txt from github.com/david47k/top-english-wordlists
           (Google Books Ngram, CC BY 3.0)
  Filter:  lowercase entries of SCOWL american-english (Debian wamerican), so names, places and foreign words drop out

Words are sorted by key sequence, then by how common they are. Every block of BLOCK words is front-coded:
a header byte (letters shared with the previous word << 4 | new letters), a rank byte (0 = most common), then the
new letters. Each block starts from scratch so it can be searched on its own.

Usage: python3 library/tools/gen_dict.py   (sudo apt install wamerican first)
'''

import os
import urllib.request

HERE    = os.path.dirname(os.path.abspath(__file__))
DL      = os.path.join(HERE, 'dl')
OUT     = os.path.join(HERE, '..', 'arduino', 'src', 't9kb_dict.c')
NGRAM   = 'https://raw.githubusercontent.com/david47k/top-english-wordlists/master/top_english_words_lower_50000.txt'
SCOWL   = '/usr/share/dict/american-english'
UA      = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/154.0.0.0 Safari/537.36'
WORDS   = 20000
MAXLEN  = 15
BLOCK   = 32
KEYS    = {c: d for d, letters in zip('23456789', ['abc', 'def', 'ghi', 'jkl', 'mno', 'pqrs', 'tuv', 'wxyz']) for c in letters}


def ranked_words():
	'''Most common first, lowercase a-z English words only'''

	path = os.path.join(DL, 'ngram50k.txt')
	if not os.path.exists(path):
		os.makedirs(DL, exist_ok=True)
		req = urllib.request.Request(NGRAM, headers={'User-Agent': UA})
		with urllib.request.urlopen(req, timeout=15) as r, open(path, 'wb') as f:
			f.write(r.read())
	english = {w.strip() for w in open(SCOWL) if w.strip().isascii() and w.strip().isalpha() and w.strip().islower()}
	english.add('i')
	words, seen = [], set()
	for w in open(path):
		w = w.strip()
		if w in english and len(w) <= MAXLEN and w not in seen:
			seen.add(w)
			words.append(w)
		if len(words) == WORDS:
			break
	return words


def main():
	words = ranked_words()
	pos   = {w: i for i, w in enumerate(words)}
	rank  = {w: i * 256 // len(words) for i, w in enumerate(words)}
	order = sorted(words, key=lambda w: (''.join(KEYS[c] for c in w), pos[w]))
	blob, index = bytearray(), []
	for i, w in enumerate(order):
		if i % BLOCK == 0:
			index.append(len(blob))
			prev = ''
		shared = 0
		while shared < min(len(prev), len(w)) and prev[shared] == w[shared]:
			shared += 1
		blob.append(shared << 4 | (len(w) - shared))
		blob.append(rank[w])
		blob += w[shared:].encode()
		prev = w

	def rows(data, fmt, per):
		return '\n'.join('\t' + ' '.join(fmt % v for v in data[i:i + per]) for i in range(0, len(data), per))

	with open(OUT, 'w') as f:
		f.write('// T9KB - Developed by acidvegas in C (https://github.com/acidvegas)\n')
		f.write('// library/arduino/src/t9kb_dict.c - generated by library/tools/gen_dict.py, do not edit\n')
		f.write('//\n')
		f.write('// %d English words. Ranking: Google Books Ngram via github.com/david47k/top-english-wordlists (CC BY 3.0).\n' % len(words))
		f.write('// Filtered against SCOWL, Copyright 2000-2011 by Kevin Atkinson (see the README for the full notice).\n\n')
		f.write('#include "t9kb_dict.h"\n\n#if T9KB_DICT\n\n')
		f.write('const uint16_t t9kb_dict_words  = %d;\n' % len(words))
		f.write('const uint16_t t9kb_dict_blocks = %d;\n' % len(index))
		f.write('const uint8_t  t9kb_dict_block  = %d;\n\n' % BLOCK)
		f.write('const uint32_t t9kb_dict_index[%d] = {\n%s\n};\n\n' % (len(index), rows(index, '%d,', 12)))
		f.write('const uint8_t t9kb_dict_data[%d] = {\n%s\n};\n\n#endif\n' % (len(blob), rows(blob, '0x%02x,', 16)))
	print('%d words, %d blocks, %d bytes data + %d bytes index' % (len(words), len(index), len(blob), len(index) * 4))


if __name__ == '__main__':
	main()
